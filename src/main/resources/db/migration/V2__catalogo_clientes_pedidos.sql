CREATE TABLE cupcake.cupcakes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(1000) NOT NULL,
    preco NUMERIC(12,2) NOT NULL CHECK (preco > 0),
    sabor VARCHAR(120) NOT NULL,
    imagem_url VARCHAR(1000),
    disponivel BOOLEAN NOT NULL,
    ativo BOOLEAN NOT NULL
);
CREATE TABLE cupcake.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    telefone VARCHAR(30) NOT NULL
);
CREATE TABLE cupcake.pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cupcake.clientes(id),
    status VARCHAR(40) NOT NULL,
    status_pagamento VARCHAR(30) NOT NULL,
    forma_pagamento VARCHAR(30),
    valor_total NUMERIC(12,2) NOT NULL CHECK (valor_total > 0),
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL,
    logradouro VARCHAR(200) NOT NULL,
    numero VARCHAR(30) NOT NULL,
    complemento VARCHAR(120),
    bairro VARCHAR(120) NOT NULL,
    cidade VARCHAR(120) NOT NULL,
    estado VARCHAR(2) NOT NULL,
    cep VARCHAR(9) NOT NULL,
    versao BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE cupcake.itens_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES cupcake.pedidos(id),
    cupcake_id BIGINT NOT NULL REFERENCES cupcake.cupcakes(id),
    nome_cupcake VARCHAR(120) NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(12,2) NOT NULL CHECK (preco_unitario > 0)
);
CREATE INDEX idx_pedidos_cliente ON cupcake.pedidos(cliente_id);
CREATE INDEX idx_itens_pedido ON cupcake.itens_pedido(pedido_id);

